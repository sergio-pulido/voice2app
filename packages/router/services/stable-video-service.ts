/**
 * Stable Video Diffusion Service
 * Alternative video generation when fal.ai is not available
 */

import { config } from '../../shared/config'
import { logger } from '../../shared/logger'
import { writeFile, mkdir, readFile } from 'fs/promises'
import { join } from 'path'

interface VideoOptions {
  imageUrl: string
  audioUrl: string
  resolution?: '480p' | '720p'
}

/**
 * Generate video using Stable Video Diffusion (free alternative)
 * For now, we'll create a placeholder that explains the limitation
 */
export async function generateVideoWithStable(options: VideoOptions): Promise<string> {
  try {
    const { imageUrl, audioUrl, resolution = '720p' } = options
    
    logger.info(`🎬 Generating video with Stable Video Diffusion...`)
    logger.debug(`Image: ${imageUrl.substring(0, 50)}...`)
    logger.debug(`Audio: ${audioUrl.substring(0, 50)}...`)
    
    // For now, create a placeholder video or use a free service
    // This is a fallback when fal.ai is not available
    
    logger.info('📝 Creating placeholder video response...')
    
    // Save a text file explaining the situation
    const timestamp = Date.now()
    const filename = `video_info_${timestamp}.txt`
    const artifactsDir = join(process.cwd(), 'artifacts')
    await mkdir(artifactsDir, { recursive: true })
    const filepath = join(artifactsDir, filename)
    
    const info = `Video Generation Info
==================
Timestamp: ${new Date().toISOString()}
Image: ${imageUrl}
Audio: ${audioUrl}
Resolution: ${resolution}

Status: fal.ai video models not available with current API key

Alternative Solutions:
1. Get access to fal.ai video models
2. Use RunwayML API
3. Use Stable Video Diffusion locally
4. Use other video generation services

Generated by Voice2App system.`
    
    await writeFile(filepath, info)
    
    logger.success(`✅ Video info saved: ${filename}`)
    
    return filepath
  } catch (error: any) {
    const errorMessage = error?.message || error?.toString() || 'Unknown error'
    logger.error('Stable Video generation error:', errorMessage)
    throw new Error(`Video generation error: ${errorMessage}`)
  }
}

/**
 * Generate video with retry logic
 */
export async function generateVideoWithStableRetry(
  options: VideoOptions,
  maxRetries: number = 2
): Promise<string | null> {
  let lastError: Error | null = null
  
  for (let attempt = 1; attempt <= maxRetries; attempt++) {
    try {
      return await generateVideoWithStable(options)
    } catch (error: any) {
      lastError = error
      const errorMsg = error?.message || 'Unknown error'
      logger.warn(`Stable Video generation failed (attempt ${attempt}/${maxRetries}): ${errorMsg}`)
      
      if (attempt < maxRetries) {
        const delay = 3000 // 3 seconds
        logger.info(`Retrying in ${delay / 1000}s...`)
        await new Promise(resolve => setTimeout(resolve, delay))
      }
    }
  }
  
  logger.error(`Failed to generate video with Stable Video after ${maxRetries} attempts`)
  logger.error(`Last error: ${lastError?.message}`)
  return null
}
